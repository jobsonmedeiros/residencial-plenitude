create or replace function public.set_apartment_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists apartments_set_updated_at on public.apartments;
create trigger apartments_set_updated_at
before update on public.apartments
for each row execute function public.set_apartment_updated_at();

