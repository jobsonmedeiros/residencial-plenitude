do $$
begin
  if exists (
    select 1
    from public.apartments
    where residential_name is null
      or trim(regexp_replace(residential_name, '[[:space:]]+', ' ', 'g')) = ''
  ) then
    raise exception 'Existem apartamentos sem nome de residencial. Corrija esses dados antes de executar esta configuração.';
  end if;

  if exists (
    select 1
    from public.apartments
    where residential_name is not null
      and trim(regexp_replace(residential_name, '[[:space:]]+', ' ', 'g')) <> ''
    group by lower(trim(regexp_replace(residential_name, '[[:space:]]+', ' ', 'g')))
    having count(distinct residential_number) > 1
  ) then
    raise exception 'Existem residenciais com nomes repetidos. Corrija os nomes antes de executar esta configuração.';
  end if;

  if exists (
    select 1
    from public.apartments
    where residential_name is not null
      and trim(regexp_replace(residential_name, '[[:space:]]+', ' ', 'g')) <> ''
    group by residential_number
    having count(distinct lower(trim(regexp_replace(residential_name, '[[:space:]]+', ' ', 'g')))) > 1
  ) then
    raise exception 'Existem unidades do mesmo residencial com nomes diferentes. Corrija os nomes antes de executar esta configuração.';
  end if;
end;
$$;

