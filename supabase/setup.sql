create table if not exists public.profiles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  role text not null default 'sales' check (role in ('admin', 'sales'))
);

create table if not exists public.apartments (
  id bigint generated by default as identity primary key,
  residential_number smallint not null check (residential_number between 1 and 32767),
  apartment_number smallint not null check (apartment_number between 1 and 32767),
  floor text not null check (length(trim(floor)) > 0),
  status text not null default 'confirmar' check (status in ('confirmar', 'disponivel', 'negociacao', 'vendido')),
  price numeric(12, 2) not null default 0 check (price >= 0),
  area numeric(8, 2),
  bedrooms smallint not null default 2 check (bedrooms between 0 and 20),
  description text not null default '',
  updated_at timestamptz not null default now(),
  unique (residential_number, apartment_number)
);

alter table public.apartments drop constraint if exists apartments_residential_number_check;
alter table public.apartments drop constraint if exists apartments_apartment_number_check;
alter table public.apartments drop constraint if exists apartments_floor_check;
alter table public.apartments
  add constraint apartments_residential_number_check check (residential_number between 1 and 32767),
  add constraint apartments_apartment_number_check check (apartment_number between 1 and 32767),
  add constraint apartments_floor_check check (length(trim(floor)) > 0);

create or replace function public.set_apartment_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists apartments_set_updated_at on public.apartments;
create trigger apartments_set_updated_at
before update on public.apartments
for each row execute function public.set_apartment_updated_at();

insert into public.apartments (residential_number, apartment_number, floor)
select residential_number, apartment_number,
  case when apartment_number <= 3 then 'Térreo' else '1º andar' end
from generate_series(1, 13) as residential_number
cross join generate_series(1, 6) as apartment_number
on conflict (residential_number, apartment_number) do nothing;

alter table public.profiles enable row level security;
alter table public.apartments enable row level security;

drop policy if exists "Anyone can view apartments" on public.apartments;
create policy "Anyone can view apartments"
on public.apartments for select
to anon, authenticated
using (true);

drop policy if exists "Admins can update apartments" on public.apartments;
create policy "Admins can update apartments"
on public.apartments for update
to authenticated
using (
  exists (
    select 1 from public.profiles
    where profiles.user_id = (select auth.uid())
      and profiles.role = 'admin'
  )
)
with check (
  exists (
    select 1 from public.profiles
    where profiles.user_id = (select auth.uid())
      and profiles.role = 'admin'
  )
);

drop policy if exists "Admins can insert apartments" on public.apartments;
create policy "Admins can insert apartments"
on public.apartments for insert
to authenticated
with check (
  exists (
    select 1 from public.profiles
    where profiles.user_id = (select auth.uid())
      and profiles.role = 'admin'
  )
);

drop policy if exists "Users can view their own profile" on public.profiles;
create policy "Users can view their own profile"
on public.profiles for select
to authenticated
using (user_id = (select auth.uid()));

grant select on public.apartments to anon, authenticated;
grant insert (residential_number, apartment_number, floor) on public.apartments to authenticated;
grant update (status, price, area, bedrooms, description) on public.apartments to authenticated;
grant select on public.profiles to authenticated;

